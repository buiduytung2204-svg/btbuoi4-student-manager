import { test, expect } from '@playwright/test';
test.use({ locale: 'vi-VN' });
test('CRUD, validation, confirmations and persistence', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByText('Chưa có sinh viên', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '+ Thêm sinh viên', exact: true }).click();
  await page.getByRole('button', { name: 'Lưu sinh viên', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Vui lòng nhập');
  await page.getByLabel('Họ tên SV', { exact: true }).fill('Nguyễn Văn An');
  await page.getByLabel('Mã số SV', { exact: true }).fill('SV001');
  await page.getByLabel('Email', { exact: true }).fill('invalid');
  await page.getByRole('button', { name: 'Lưu sinh viên', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Email'.toLowerCase());
  await page.getByLabel('Email', { exact: true }).fill('an@example.com');
  await page.getByRole('button', { name: 'Lưu sinh viên', exact: true }).click();
  await expect(page.getByText('Thông tin sinh viên', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Nguyễn Văn An, SV001', exact: true }).click();
  await page.getByRole('button', { name: 'Sửa thông tin', exact: true }).click();
  await page.getByLabel('Họ tên SV', { exact: true }).fill('Nguyễn Văn Bình');
  await page.getByRole('button', { name: 'Lưu sinh viên', exact: true }).click();
  await expect(page.getByText('Bạn có muốn sửa thông tin SV không?', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Không', exact: true }).click();
  await expect(page.getByLabel('Họ tên SV', { exact: true })).toHaveValue('Nguyễn Văn Bình');
  await page.getByRole('button', { name: 'Lưu sinh viên', exact: true }).click();
  await page.getByRole('button', { name: 'Có', exact: true }).click();
  await expect(page.getByText('Nguyễn Văn Bình', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Xóa sinh viên', exact: true }).click();
  await page.getByRole('button', { name: 'Không', exact: true }).click();
  await expect(page.getByText('Thông tin sinh viên', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Xóa sinh viên', exact: true }).click();
  await page.getByRole('button', { name: 'Có', exact: true }).click();
  await expect(page.getByText('Chưa có sinh viên', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Chưa có sinh viên', { exact: true })).toBeVisible();
});
test('English follows device locale', async ({ browser }) => {
  const context = await browser.newContext({ locale: 'en-US' });
  const page = await context.newPage();
  await page.goto('/');
  await expect(page.getByText('Student Manager', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '+ Add student', exact: true })).toBeVisible();
  await context.close();
});
